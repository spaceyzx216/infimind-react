import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:15173')
parser.add_argument('--output', required=True)
args = parser.parse_args()
output = Path(args.output).resolve()
output.mkdir(parents=True, exist_ok=True)
handbook = '合成员工手册\n第一章 考勤制度\n第一条 员工迟到时，公司应先提醒并允许补正记录。\n第二条 员工忘打卡时，公司须核实实际出勤。\n第二章 奖惩制度\n第三条 员工迟到一次，公司可以解除劳动合同。\n'
home = '员工手册诊断\n员工手册分析助手\n您好，请直接上传需要分析的员工手册图片。\n发送消息\n由扣子提供'
errors = []
checks = []
with sync_playwright() as p:
    edge = Path('C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe')
    browser = p.chromium.launch(headless=True, **({'executable_path': str(edge)} if edge.exists() else {}))
    context = browser.new_context(viewport={'width': 1440, 'height': 1000})
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(args.url + '/labor-consult')
    page.wait_for_load_state('networkidle')
    page.get_by_role('button', name='更多功能', exact=True).click()
    expect(page.get_by_role('menuitem', name='员工手册诊断', exact=True)).to_be_visible()
    page.get_by_role('menuitem', name='员工手册诊断', exact=True).click()
    expect(page).to_have_url(args.url + '/tools/handbook')
    checks.append('从工作区更多功能进入员工手册诊断')
    expect(page.locator('.chat-title strong')).to_have_text('新的员工手册诊断')
    expect(page.locator('.sidebar-brand')).to_have_text('法飞飞')
    assert page.get_by_role('combobox').count() == 0, '页面不能要求选择完整手册或片段'
    page.screenshot(path=str(output / 'handbook-empty-desktop.png'), full_page=True)
    page.get_by_role('textbox', name='员工手册正文', exact=True).fill(home)
    page.get_by_role('button', name='开始诊断', exact=True).click()
    expect(page.get_by_text('材料待处理', exact=True)).to_be_visible(timeout=15000)
    assert page.get_by_test_id('handbook-finding').count() == 0
    checks.append('首页说明被拦截，无虚构条款结果')
    page.get_by_role('button', name='新诊断', exact=True).click()
    page.get_by_role('textbox', name='员工手册正文', exact=True).fill(handbook)
    page.get_by_role('button', name='开始诊断', exact=True).click()
    expect(page.get_by_text('本次正文检查完成', exact=True)).to_be_visible(timeout=30000)
    expect(page.get_by_role('heading', name='迟到处理规则前后需协调')).to_be_visible()
    first_id = page.url.split('taskId=')[1].split('&')[0]
    page.get_by_role('button', name='定位原文：迟到处理规则前后需协调 1', exact=True).click()
    expect(page.locator('.hb-source .quote-mark').first).to_be_visible()
    assert '迟到' in ''.join(page.locator('.hb-source .quote-mark').all_inner_texts())
    page.screenshot(path=str(output / 'handbook-report-desktop.png'), full_page=True)
    page.get_by_role('button', name='关闭原文', exact=True).click()
    checks.append('跨章节问题关联原文并高亮')
    page.reload()
    page.wait_for_load_state('networkidle')
    expect(page.get_by_text('本次正文检查完成', exact=True)).to_be_visible()
    expect(page.get_by_role('heading', name='迟到处理规则前后需协调')).to_be_visible()
    checks.append('刷新恢复诊断与原文')
    page.get_by_role('textbox', name='报告追问', exact=True).fill('解释迟到问题')
    page.get_by_role('button', name='发送追问', exact=True).click()
    expect(page.get_by_role('button', name='停止检查', exact=True)).to_be_visible()
    page.reload()
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='迟到处理规则前后需协调')).to_be_visible()
    expect(page.get_by_text('测试回复：请结合已定位原文核对适用条件；当前未核实程序证据或法律条文。', exact=True)).to_be_visible(timeout=15000)
    page.reload()
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='迟到处理规则前后需协调')).to_be_visible()
    checks.append('追问进行中及完成后刷新保留原报告')
    page.get_by_role('button', name='提交新版正文', exact=True).click()
    page.get_by_role('textbox', name='员工手册正文', exact=True).fill('员工须按实际出勤记录申请考勤补正。')
    assert page.get_by_role('heading', name='迟到处理规则前后需协调').count() == 0, '新版正文不能沿用旧诊断'
    page.get_by_role('button', name='开始诊断', exact=True).click()
    expect(page.get_by_text('本次正文检查完成', exact=True)).to_be_visible(timeout=15000)
    assert page.get_by_test_id('handbook-finding').count() == 0
    checks.append('新版正文清除旧结果，短条款独立诊断')
    page.get_by_role('button', name='新诊断', exact=True).click()
    page.get_by_role('textbox', name='员工手册正文', exact=True).fill(handbook)
    page.get_by_role('button', name='开始诊断', exact=True).click()
    page.get_by_role('button', name='停止检查', exact=True).click()
    expect(page.get_by_role('button', name='继续未完成检查', exact=True)).to_be_visible(timeout=15000)
    page.get_by_role('button', name='继续未完成检查', exact=True).click()
    expect(page.get_by_text('本次正文检查完成', exact=True)).to_be_visible(timeout=30000)
    checks.append('停止与恢复检查')
    page.goto(args.url + '/tools/handbook?taskId=' + first_id)
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='迟到处理规则前后需协调')).to_be_visible()
    page.get_by_role('button', name='删除诊断：员工手册诊断', exact=True).first.click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_role('button', name='保留', exact=True).click()
    checks.append('删除前确认，取消保留记录')
    mobile = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True)
    mobile_page = mobile.new_page()
    mobile_page.on('pageerror', lambda error: errors.append(str(error)))
    mobile_page.goto(args.url + '/tools/handbook?taskId=' + first_id)
    mobile_page.wait_for_load_state('networkidle')
    expect(mobile_page.get_by_role('heading', name='迟到处理规则前后需协调')).to_be_visible()
    mobile_page.get_by_role('button', name='定位原文：迟到处理规则前后需协调 1', exact=True).click()
    expect(mobile_page.locator('.hb-source .quote-mark').first).to_be_visible()
    mobile_page.screenshot(path=str(output / 'handbook-source-mobile.png'), full_page=True)
    mobile_page.get_by_role('button', name='关闭原文', exact=True).click()
    assert mobile_page.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 1')
    checks.append('手机端原文查看及无横向溢出')
    assert not errors, errors
    (output / 'handbook-ui-results.json').write_text(json.dumps({'passed': checks, 'pageErrors': errors}, ensure_ascii=False, indent=2), encoding='utf-8')
    mobile.close()
    context.close()
    browser.close()
print(json.dumps({'passed': checks, 'output': str(output)}, ensure_ascii=False))
