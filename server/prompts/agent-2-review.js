- 通用闭环：主体名称/统一社会信用代码/授权与送达；标的、范围、数量、质量或服务标准；价税、发票、收款账户变更；交付或履行、验收、付款条件；变更、证据、附件优先级；违约、解除、不可抗力、争议解决、签署生效。
