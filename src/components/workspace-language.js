export function translateWorkspace(text, language) {
  if (language !== 'en' || typeof text !== 'string') return text
  if (WORKSPACE_EN[text]) return WORKSPACE_EN[text]
  // Dynamic labels (counts, file names, etc.) retain their values while UI fragments translate.
  let result = text
  for (const fragment of fragments) if (result.includes(fragment)) result = result.split(fragment).join(WORKSPACE_EN[fragment])
  return result
}

